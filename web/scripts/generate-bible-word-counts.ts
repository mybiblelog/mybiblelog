/**
 * Regenerates app/helpers/bible-book-word-counts.ts via the scrollmapper
 * bible_databases JSON exports: the 66 common books from the Berean Standard
 * Bible (public domain / CC0 since 2023-04-30), and the deuterocanonical books
 * from the KJV 1611 Apocrypha (public domain), which the BSB doesn't include and
 * whose versification our DC verse counts already follow. Word counts drive the
 * reading-time estimates on the public Books of the Bible pages and the
 * reading-time guide.
 *
 * Usage: npx tsx ./scripts/generate-bible-word-counts.ts
 * Also prints a markdown table (book, chapters, verses, words, minutes at
 * 238 wpm) for pasting into the "how long does it take" guide.
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
// @mybiblelog/shared is CJS; see scripts/i18n/verify-i18n-keys.ts
import shared from '@mybiblelog/shared';

const { Bible } = shared;

const SOURCE_URL = 'https://raw.githubusercontent.com/scrollmapper/bible_databases/2025/formats/json/BSB.json';
const DC_SOURCE_URL = 'https://raw.githubusercontent.com/scrollmapper/bible_databases/2025/formats/json/KJVA.json';
const WORDS_PER_MINUTE = 238;

type BibleJson = {
  books: { name: string; chapters: { verses: { text: string }[] }[] }[];
};
type BibleJsonBook = BibleJson['books'][number];

// KJVA names that differ from our English book names.
const KJVA_NAMES: Record<string, string> = {
  '1 Maccabees': 'I Maccabees',
  '2 Maccabees': 'II Maccabees',
};

const countWords = (text: string): number => (text.match(/[A-Za-z0-9’']+/g) ?? []).length;

const countBookWords = (book: BibleJsonBook): number =>
  book.chapters.reduce((sum, chapter) =>
    sum + chapter.verses.reduce((verseSum, verse) => verseSum + countWords(verse.text), 0), 0);

const download = async (url: string): Promise<BibleJson> => {
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`Failed to download ${url}: ${res.status}`);
  }
  return await res.json() as BibleJson;
};

const main = async () => {
  const [bsb, kjva] = await Promise.all([download(SOURCE_URL), download(DC_SOURCE_URL)]);
  if (bsb.books.length !== Bible.getBookCount()) {
    throw new Error(`Expected ${Bible.getBookCount()} books, got ${bsb.books.length}`);
  }

  // The BSB export lists books in canonical order, so position n is bibleOrder n + 1.
  const commonCounts = bsb.books.map(countBookWords);

  // DC books are matched by name. Whole-book sums sidestep versification
  // differences (the KJV numbers the Additions to Esther 10:4–16:24).
  const dcCounts = Bible.getAllBooks()
    .filter(book => book.deuterocanonical)
    .map((book) => {
      const name = Bible.getBookName(book.bibleOrder);
      const source = kjva.books.find(b => b.name === (KJVA_NAMES[name] ?? name));
      if (!source) {
        throw new Error(`No KJVA book found for ${name}`);
      }
      return countBookWords(source);
    });

  const wordCounts = [...commonCounts, ...dcCounts];
  if (wordCounts.length !== Bible.getAllBooks().length) {
    throw new Error(`Expected ${Bible.getAllBooks().length} books, got ${wordCounts.length}`);
  }

  const outFile = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../app/helpers/bible-book-word-counts.ts');
  const lines = wordCounts.map((count, i) => `  ${count}, // ${Bible.getBookName(i + 1)}`);
  await fs.writeFile(outFile, `// Generated by scripts/generate-bible-word-counts.ts — do not edit by hand.
// Word counts per book (index 0 = Genesis, index n = bibleOrder n + 1).
// Books 1-66 from the Berean Standard Bible (public domain / CC0 since 2023-04-30): ${SOURCE_URL}
// Deuterocanonical books 67-77 from the KJV 1611 Apocrypha (public domain): ${DC_SOURCE_URL}
const bibleBookWordCounts: readonly number[] = [
${lines.join('\n')}
];

export default bibleBookWordCounts;
`);

  console.log('| Book | Chapters | Verses | Words | Reading time |');
  console.log('|---|---:|---:|---:|---:|');
  wordCounts.forEach((count, i) => {
    const book = i + 1;
    const minutes = Math.max(1, Math.round(count / WORDS_PER_MINUTE));
    console.log(`| ${Bible.getBookName(book)} | ${Bible.getBookChapterCount(book)} | ${Bible.getBookVerseCount(book).toLocaleString('en-US')} | ${count.toLocaleString('en-US')} | ${minutes} min |`);
  });
  const total = commonCounts.reduce((a, b) => a + b, 0);
  const ot = commonCounts.slice(0, 39).reduce((a, b) => a + b, 0);
  console.log(`\nTotal ${total} (OT ${ot}, NT ${total - ot}); ${(total / WORDS_PER_MINUTE / 60).toFixed(1)} h`);
};

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
