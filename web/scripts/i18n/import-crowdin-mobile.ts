/**
 * Regenerates the non-English mobile/src/i18n/<locale>.ts files from
 * web/i18n/locales/crowdin/mobile/<locale>.json (after `crowdin download --config crowdin.mobile.yml`).
 *
 * Usage: npm run i18n:import-crowdin-mobile
 */
import { execFileSync } from 'node:child_process';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { getLocaleCodes } from '@mybiblelog/shared';
import { isPlainObject, mobileCrowdinDir, mobileLocalesDir } from './crowdin-bundle-shared';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const NUXT_ROOT = path.resolve(SCRIPT_DIR, '../..');

type MobileTable = Record<string, string>;

async function readMobileBundle(filePath: string): Promise<MobileTable> {
  const parsed = JSON.parse(await fs.readFile(filePath, 'utf8')) as unknown;
  if (!isPlainObject(parsed)) {
    throw new Error(`${filePath}: root must be a JSON object`);
  }
  for (const [k, v] of Object.entries(parsed)) {
    if (typeof v !== 'string') {
      throw new Error(`${filePath}: ${k} must be a string`);
    }
  }
  return parsed as MobileTable;
}

const MOBILE_KEY_LINE_RE = /^ {2}([a-zA-Z_$][\w$]*):/;

/**
 * Regenerates each non-English mobile table using en.ts as the layout template (key order, blank
 * lines, section comments), so translations can't drift structurally from the source. en.ts itself
 * is developer-edited and never written.
 */
async function writeMobileLocaleFiles(
  bundles: Record<string, MobileTable>,
  localeCodes: string[],
): Promise<void> {
  const dir = mobileLocalesDir(NUXT_ROOT);
  const templateLines = (await fs.readFile(path.join(dir, 'en.ts'), 'utf8')).split('\n');
  const start = templateLines.findIndex(l => l.startsWith('export const en = {'));
  const end = templateLines.findIndex(l => l.startsWith('} as const'));
  if (start < 0 || end < start) {
    throw new Error(`${dir}/en.ts: expected "export const en = {" ... "} as const"`);
  }
  const body = templateLines.slice(start + 1, end);
  const enMessages = bundles.en;

  const written: string[] = [];
  for (const loc of localeCodes.filter(l => l !== 'en')) {
    const messages = bundles[loc];
    const out: string[] = [];
    for (const line of body) {
      const key = MOBILE_KEY_LINE_RE.exec(line)?.[1];
      if (key) {
        const value = messages[key] ?? enMessages[key];
        if (value === undefined) {
          throw new Error(`${key} missing from the en bundle`);
        }
        out.push(`  ${key}: ${JSON.stringify(value)},`);
      }
      else if (line.trim() === '' || line.trim().startsWith('//')) {
        out.push(line);
      }
    }
    const file = path.join(dir, `${loc}.ts`);
    await fs.writeFile(
      file,
      `import type { en } from "./en";\n\n// Regenerated by \`npm run -w web i18n:import-crowdin-mobile\` using en.ts as the layout; translate in Crowdin.\n// \`satisfies\` makes a missing or stray key a type error instead of a silent runtime fallback.\nexport const ${loc} = {\n${out.join('\n')}\n} as const satisfies Record<keyof typeof en, string>;\n`,
      'utf8',
    );
    written.push(file);
  }

  const mobileRoot = path.resolve(dir, '..', '..');
  execFileSync('npx', ['prettier', '--write', ...written.map(f => path.relative(mobileRoot, f))], {
    cwd: mobileRoot,
    stdio: 'inherit',
  });
  console.log(`Wrote ${written.length} mobile locale file(s) in ${path.relative(process.cwd(), dir)}`);
}

async function main() {
  const localeCodes = getLocaleCodes();
  const dir = mobileCrowdinDir(NUXT_ROOT);
  const bundles: Record<string, MobileTable> = {};
  const missing: string[] = [];
  for (const loc of localeCodes) {
    const fp = path.join(dir, `${loc}.json`);
    try {
      bundles[loc] = await readMobileBundle(fp);
    }
    catch (err) {
      if ((err as NodeJS.ErrnoException).code !== 'ENOENT') {
        throw err;
      }
      missing.push(fp);
    }
  }
  if (missing.length > 0) {
    console.error('Missing mobile Crowdin bundle file(s):');
    for (const m of missing) {
      console.error(`  ${m}`);
    }
    process.exitCode = 1;
    return;
  }
  await writeMobileLocaleFiles(bundles, localeCodes);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
